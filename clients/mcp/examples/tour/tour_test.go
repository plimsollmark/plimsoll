// committed is the recording the trainer page loads.
const committed = "../../../../docs/trainers/mcp-tour.js"

// scenarios are the examples the page shows, in order.
var scenarios = []string{"check-dont-guess", "your-file", "notebook", "debug-loop", "no-network", "two-languages", "runaway-loop", "prove-it-later", "cap"}

func load(t *testing.T) (*Tour, []byte) {
	t.Helper()
	data, err := os.ReadFile(committed)
	if err != nil {
		t.Fatal(err)
	}
	tour, err := decode(data)
	if err != nil {
		t.Fatalf("%s does not parse: %v", committed, err)
	}
	return tour, data
}

func TestRecordingParsesAndHoldsEveryScenario(t *testing.T) {
	tour, data := load(t)
	if !bytes.HasPrefix(data, []byte("// Generated by clients/mcp/examples/tour at ")) || !bytes.Contains(data, []byte("Do not edit it by hand")) {
		t.Error("the file does not open with the comment saying it is generated and must not be edited by hand")
	}
	if !strings.HasPrefix(tour.Method, "Scripted calls, made the way a model makes them") {
		t.Errorf("the method does not say the calls are scripted: %q", tour.Method)
	}
	var ids []string
	for i, sc := range tour.Scenarios {
		ids = append(ids, sc.ID)
		if sc.Number != i+1 || sc.Title == "" || sc.Ask == "" || sc.Shows == "" || sc.Observed == "" || len(sc.Steps) == 0 || len(sc.Claims) == 0 {
			t.Errorf("scenario %d (%s) is missing its number, text, steps or claims", i+1, sc.ID)
		}
		for _, st := range sc.Steps {
			if !json.Valid(st.Arguments) || !json.Valid(st.Result) || st.Intent == "" {
				t.Errorf("%s: a %s step lacks its intent, arguments or result", sc.ID, st.Tool)
			}
		}
	}
	if !slices.Equal(ids, scenarios) {
		t.Errorf("scenarios %v, want %v", ids, scenarios)
	}
	if tour.ServerInfo == nil || tour.ServerInfo.Tool != "server_info" {
		t.Error("the recording has no server_info call")
	}
}

// A change to the server's tools (a name, a description, a schema) changes its surface
// digest, so the recording is stale until the tour is run again.
func TestRecordingMatchesTheServersTools(t *testing.T) {
	tour, _ := load(t)
	env := map[string]string{"PLIMSOLL_URL": "http://127.0.0.1:1"} // nothing listens: server_info needs no daemon for its tools
	for _, kv := range settings {
		k, v, _ := strings.Cut(kv, "=")
		env[k] = v
	}
	cfg, err := server.FromEnv(func(k string) string { return env[k] })
	if err != nil {
		t.Fatal(err)
	}
	s, err := server.New(cfg)
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	ct, st := mcp.NewInMemoryTransports()
	ss, err := s.MCP().Connect(ctx, st, nil)
	if err != nil {
		t.Fatal(err)
	}
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "test", Version: "0"}, nil).Connect(ctx, ct, nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_ = cs.Close()
		_ = ss.Close()
		closing, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		_ = s.Close(closing)
	})
	res, err := cs.CallTool(ctx, &mcp.CallToolParams{Name: "server_info", Arguments: map[string]any{}})
	if err != nil || res.IsError {
		t.Fatalf("server_info: %v %v", err, res)
	}
	var info struct {
		Version       string   `json:"version"`
		Tools         []string `json:"tools"`
		SurfaceDigest string   `json:"surfaceDigest"`
	}
	b, _ := json.Marshal(res.StructuredContent)
	if err := json.Unmarshal(b, &info); err != nil {
		t.Fatal(err)
	}
	stale := " (the server changed since the recording: rerun the tour, clients/mcp/examples/tour/README.md)"
	if tour.SurfaceDigest != info.SurfaceDigest {
		t.Errorf("recorded surface digest %s, the server's is %s%s", tour.SurfaceDigest, info.SurfaceDigest, stale)
	}
	if tour.Server.Version != info.Version {
		t.Errorf("recorded server version %s, the server is %s%s", tour.Server.Version, info.Version, stale)
	}
	if !slices.Equal(tour.Tools, info.Tools) {
		t.Errorf("recorded tools %v, the server registers %v%s", tour.Tools, info.Tools, stale)
	}
	var listed []struct {
		Name string `json:"name"`
	}
	if err := json.Unmarshal(tour.ToolList, &listed); err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, l := range listed {
		names = append(names, l.Name)
	}
	slices.Sort(names)
	if !slices.Equal(names, info.Tools) {
		t.Errorf("recorded tools/list %v, the server registers %v%s", names, info.Tools, stale)
	}
	for _, sc := range tour.Scenarios {
		for _, step := range sc.Steps {
			if !slices.Contains(info.Tools, step.Tool) {
				t.Errorf("%s calls %s, which the server does not register%s", sc.ID, step.Tool, stale)
			}
		}
	}
}

// The receipt verifies as the page verifies it, with the embedded public key over the
// PAE, and as plimsoll-attest verify-entry does.
func TestRecordedReceiptVerifies(t *testing.T) {
	tour, _ := load(t)
	var rc *Receipt
	var first map[string]any
	for _, sc := range tour.Scenarios {
		if sc.Receipt != nil {
			rc = sc.Receipt
		}
		if sc.ID == "check-dont-guess" {
			_ = json.Unmarshal(sc.Steps[0].Result, &first)
		}
	}
	if rc == nil {
		t.Fatal("no scenario carries a receipt")
	}
	raw, err := base64.StdEncoding.DecodeString(rc.PublicKeyRaw)
	if err != nil || len(raw) != ed25519.PublicKeySize {
		t.Fatalf("publicKeyRaw is not a base64 Ed25519 public key: %v", err)
	}
	pub := ed25519.PublicKey(raw)
	fromPEM, err := attest.ParsePublicKey([]byte(rc.PublicKeyPEM))
	if err != nil || !fromPEM.Equal(pub) {
		t.Fatalf("publicKeyPem is not the key in publicKeyRaw: %v", err)
	}
	if attest.KeyID(pub) != rc.KeyID {
		t.Errorf("keyId %s, the key's is %s", rc.KeyID, attest.KeyID(pub))
	}
	sum := sha256.Sum256([]byte(rc.Line))
	if hex.EncodeToString(sum[:]) != rc.LineSHA256 {
		t.Error("lineSha256 is not the SHA-256 of the line")
	}
	var e attest.Entry
	if err := json.Unmarshal([]byte(rc.Line), &e); err != nil {
		t.Fatal(err)
	}
	payload, err := base64.StdEncoding.DecodeString(e.Envelope.Payload)
	if err != nil || len(e.Envelope.Signatures) != 1 {
		t.Fatalf("the envelope's payload or signatures: %v", err)
	}
	sig, err := base64.StdEncoding.DecodeString(e.Envelope.Signatures[0].Sig)
	if err != nil {
		t.Fatal(err)
	}
	pae := attest.PAE(e.Envelope.PayloadType, payload)
	if !ed25519.Verify(pub, pae, sig) {
		t.Error("the record's signature does not verify over the PAE with the embedded public key")
	}
	paeSum := sha256.Sum256(pae)
	if rc.Signed.Message.Bytes != len(pae) || rc.Signed.Message.SHA256 != hex.EncodeToString(paeSum[:]) || rc.Signed.Message.Payload.Bytes != len(payload) {
		t.Error("the note on what is signed does not describe this line's signed bytes")
	}
	flipped := slices.Clone(pae)
	flipped[len(flipped)/2] ^= 1
	if ed25519.Verify(pub, flipped, sig) {
		t.Error("a signature that verifies with a byte flipped checks nothing")
	}
	var stored, signed any
	_ = json.Unmarshal(rc.Statement, &stored)
	_ = json.Unmarshal(payload, &signed)
	if !jsonEqual(stored, signed) {
		t.Error("statement is not the signed payload")
	}
	rec, link, err := attest.VerifyEntry(attest.NewVerifier(pub), e)
	if err != nil {
		t.Fatalf("attest.VerifyEntry: %v", err)
	}
	if link.Index != uint64(rc.LineNumber) {
		t.Errorf("the line's link says line %d, the receipt %d", link.Index, rc.LineNumber)
	}
	if rec.SHA256 != rc.RecordSHA256 || rec.SHA256 != first["recordSha256"] {
		t.Errorf("the signed record %s is not example 1's (%v, receipt %s)", rec.SHA256, first["recordSha256"], rc.RecordSHA256)
	}
	if rc.VerifyEntry.ExitCode != 0 || !strings.HasPrefix(rc.VerifyEntry.Output, "entry verified") {
		t.Errorf("verify-entry did not accept the line: %+v", rc.VerifyEntry)
	}
}

func jsonEqual(a, b any) bool {
	x, _ := json.Marshal(a)
	y, _ := json.Marshal(b)
	return bytes.Equal(x, y)
}

var (
	secretKey = regexp.MustCompile(`(?i)token|secret|password|authorization|cookie|api_?key`)
	// digestKey names a value that is a digest (or, for session, a fingerprint).
	digestKey  = regexp.MustCompile(`(?i)sha256|keyid|digest|^session$`)
	binaryKeys = map[string]bool{"line": true, "publicKeyPem": true, "publicKeyRaw": true}
	// The long strings a recording legitimately holds besides digests.
	handle      = regexp.MustCompile(`sbx_[A-Za-z0-9_-]{22}`)
	receiptFile = regexp.MustCompile(`(runs|session)-[0-9A-Za-z-]+\.jsonl`)
	hexRun      = regexp.MustCompile(`[0-9a-f]{16,}`)
	// tokenish is a long run of the characters caller tokens are made of; the tokens
	// plimsoll-clients makes are lowercase hex, which hexRun handles.
	tokenish = regexp.MustCompile(`[A-Za-z0-9_-]{24,}`)
)

// The recording holds no credential and no private key: no key named for one, no long
// string a token could be (a hex string must be a digest the recording states as one),
// and in the receipt line nothing but example 1's call.
func TestRecordingHoldsNoSecret(t *testing.T) {
	tour, data := load(t)
	for _, bad := range []string{"PRIVATE KEY", "MC4CAQAwBQYDK2VwBCIEI", "Bearer ", "PLIMSOLL_TOKEN"} {
		// MC4CAQAwBQYDK2VwBCIEI is how every Ed25519 PKCS #8 private key starts in base64.
		if bytes.Contains(data, []byte(bad)) {
			t.Errorf("the recording contains %q", bad)
		}
	}
	var generic any
	body := bytes.TrimSuffix(data[bytes.Index(data, []byte(prefix))+len(prefix):], []byte(suffix))
	if err := json.Unmarshal(body, &generic); err != nil {
		t.Fatal(err)
	}
	digests := map[string]bool{}
	declared(generic, "", digests)
	walk(t, "MCP_TOUR", generic, digests)

	var first *Scenario
	var rc *Receipt
	for _, sc := range tour.Scenarios {
		if sc.ID == "check-dont-guess" {
			first = sc
		}
		if sc.Receipt != nil {
			rc = sc.Receipt
		}
	}
	if first == nil || rc == nil {
		t.Fatal("no example 1 or no receipt")
	}
	var sent runArgs
	var got struct{ Stdout, Stderr string }
	_ = json.Unmarshal(first.Steps[0].Arguments, &sent)
	_ = json.Unmarshal(first.Steps[0].Result, &got)
	// The recording predates the daemon's Run cell: its first example ran as a project
	// carrying the runner the daemon now holds (sandbox/cellrunner).
	runner, err := os.ReadFile("../../../../sandbox/cellrunner/run.py")
	if err != nil {
		t.Fatal(err)
	}
	var e attest.Entry
	if err := json.Unmarshal([]byte(rc.Line), &e); err != nil {
		t.Fatal(err)
	}
	req, resp, err := e.Messages()
	if err != nil {
		t.Fatal(err)
	}
	files := map[string]string{}
	for _, f := range req.GetProject().GetFiles() {
		files[f.GetPath()] = f.GetContent()
	}
	if len(files) != 2 || files[".plimsoll/cell.py"] != sent.Code || files[".plimsoll/run.py"] != string(runner) {
		t.Errorf("the receipt line's request holds more than example 1's code and the server's runner: %v", slices.Sorted(maps.Keys(files)))
	}
	steps := resp.GetProject().GetSteps()
	if len(steps) != 1 || string(steps[0].GetStdout()) != got.Stdout || string(steps[0].GetStderr()) != got.Stderr {
		t.Error("the receipt line's response holds output other than example 1's")
	}
}

// declared collects the strings stated as digests.
func declared(v any, key string, out map[string]bool) {
	switch v := v.(type) {
	case map[string]any:
		for k, x := range v {
			declared(x, k, out)
		}
	case []any:
		for _, x := range v {
			declared(x, key, out)
		}
	case string:
		if digestKey.MatchString(key) && hexRun.MatchString(v) {
			out[v] = true
		}
	}
}

func walk(t *testing.T, path string, v any, digests map[string]bool) {
	t.Helper()
	switch v := v.(type) {
	case map[string]any:
		for k, x := range v {
			if secretKey.MatchString(k) {
				t.Errorf("%s has a key named %q", path, k)
			}
			if binaryKeys[k] || digestKey.MatchString(k) {
				continue
			}
			walk(t, path+"."+k, x, digests)
		}
	case []any:
		for _, x := range v {
			walk(t, path+"[]", x, digests)
		}
	case string:
		s := receiptFile.ReplaceAllString(handle.ReplaceAllString(v, ""), "")
		for _, loc := range hexRun.FindAllStringIndex(s, -1) {
			h, before := s[loc[0]:loc[1]], s[:loc[0]]
			if !strings.ContainsAny(h, "abcdef") {
				continue // a number, such as 2**61 - 1
			}
			if !strings.HasSuffix(before, "sha256:") && !strings.HasSuffix(before, "sha256 ") && !isDeclared(h, digests) {
				t.Errorf("%s holds a hex string the recording states nowhere as a digest: %q", path, h)
			}
		}
		for _, m := range tokenish.FindAllString(hexRun.ReplaceAllString(s, ""), -1) {
			digit := strings.ContainsAny(m, "0123456789")
			letter := strings.ContainsFunc(m, unicode.IsLetter)
			mixed := strings.ContainsFunc(m, unicode.IsUpper) && strings.ContainsFunc(m, unicode.IsLower) && !strings.ContainsAny(m, "_-")
			if (digit && letter) || mixed {
				t.Errorf("%s holds a string that looks like a token: %q", path, m)
			}
		}
	}
}

// isDeclared reports whether h is a stated digest or the shortened form of one.
func isDeclared(h string, digests map[string]bool) bool {
	for d := range digests {
		if strings.HasPrefix(d, h) {
			return true
		}
	}
	return false
}
