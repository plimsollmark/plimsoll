package main

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/plimsollmark/plimsoll/sandbox"
)

// renderGranted writes the Python and TypeScript clients' copies of what a granted call
// of a code tool writes into its project (sandbox/hostclient.go): the Python module
// plimsoll_host and where it goes, the providers whose Python steps can reach the broker,
// and, for the TypeScript tool, each language's granted cell form (GrantedCellProject:
// the runner a fresh cell runs under, which a granted call cannot be, since a cell
// carries no grant). One source, so the module, the runners and the provider list the
// clients send cannot drift from the daemon's.
func renderGranted() (py, ts []byte, err error) {
	var p, t bytes.Buffer
	p.WriteString(`# Code generated by internal/wiretables (make generate). DO NOT EDIT.
"""What a granted call of a code tool writes into its project, from package sandbox
(hostclient.go): the Python module plimsoll_host, where it goes, and the providers whose
Python steps can reach the broker through it."""

from typing import Tuple
`)
	t.WriteString(`// Code generated by internal/wiretables (make generate). DO NOT EDIT.
// What a granted call of a code tool writes into its project, from package sandbox
// (hostclient.go, cell_fresh.go): the Python module plimsoll_host, where it goes, the
// providers whose Python steps can reach the broker through it, and each language's
// granted cell form.
`)
	consts := []constant{
		{"HOST_MODULE_PATH", "Where a granted Python call carries plimsoll_host (sandbox.HostClientPythonPath).", sandbox.HostClientPythonPath},
		{"HOST_MODULE_DIR", "The directory a granted Python step puts on its import path (sandbox.HostClientPythonDir).", sandbox.HostClientPythonDir},
		{"HOST_MODULE_SOURCE", "plimsoll_host, the standard-library client a granted Python step calls the broker with (sandbox.HostClientPython).", sandbox.HostClientPython},
		{"PYTHON_GRANT_PROVIDERS", "The providers whose granted project steps, Python's included, get the broker's socket (sandbox.PythonGrantProviders).", sandbox.PythonGrantProviders},
	}
	for _, c := range consts {
		if s, ok := c.value.(string); ok && strings.ContainsAny(s, "\n\"\\") {
			// Go's quoting of printable ASCII and newlines is a valid Python and
			// JavaScript literal (TestGrantedCellProject keeps the module ASCII).
			fmt.Fprintf(&p, "\n# %s\n%s: str = %q\n", c.doc, c.name, s)
			fmt.Fprintf(&t, "\n/** %s */\nexport const %s = %q;\n", c.doc, c.name, s)
			continue
		}
		pv, pt, err := pythonValue(c.value)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", c.name, err)
		}
		tv, _ := typescriptValue(c.value)
		fmt.Fprintf(&p, "\n# %s\n%s: %s = %s\n", c.doc, c.name, pt, pv)
		fmt.Fprintf(&t, "\n/** %s */\nexport const %s = %s;\n", c.doc, c.name, tv)
	}
	// The granted cell form, per language: the files beside the cell's code, where the
	// code goes, and the step. The code is a marker here, found by its content.
	const marker = "\x00cell code\x00"
	t.WriteString("\n/** Each language's granted cell form (sandbox.GrantedCellProject): the files written beside the cell's code, the path the code goes to, and the one step. */\n")
	t.WriteString("export const GRANTED_CELL = {\n")
	for _, l := range sandbox.Languages {
		files, step := sandbox.GrantedCellProject(sandbox.CellRequest{Language: l, Code: marker})
		code := ""
		fmt.Fprintf(&t, "  %s: {\n    files: [\n", l)
		for _, f := range files {
			if f.Content == marker {
				code = f.Path
				continue
			}
			fmt.Fprintf(&t, "      { path: %q, content: %q },\n", f.Path, f.Content)
		}
		if code == "" {
			return nil, nil, fmt.Errorf("granted %s cell: no file holds the code", l)
		}
		fmt.Fprintf(&t, "    ],\n    codePath: %q,\n    step: %q,\n  },\n", code, step)
	}
	t.WriteString("} as const;\n")
	// A JavaScript cell as a snippet that prints its final value, for a daemon that runs
	// snippets only (sandbox.SnippetCell): the text before and after the code as a JSON
	// string literal.
	const quoted = `"plimsoll-cell-code-marker"`
	before, after, ok := strings.Cut(sandbox.SnippetCell("plimsoll-cell-code-marker"), quoted)
	if !ok || strings.Contains(after, quoted) {
		return nil, nil, fmt.Errorf("sandbox.SnippetCell does not hold its code once as a JSON string")
	}
	t.WriteString("\n/** A JavaScript cell as a snippet that prints its final value (sandbox.SnippetCell): SNIPPET_CELL[0], the code as a JSON string literal, SNIPPET_CELL[1]. */\n")
	fmt.Fprintf(&t, "export const SNIPPET_CELL = [%q, %q] as const;\n", before, after)
	return p.Bytes(), t.Bytes(), nil
}
